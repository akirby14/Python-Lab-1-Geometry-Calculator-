def calc_area(answer):
    width = float(input("\nEnter the width of the rectangle: "))
    height = float(input("\nEnter the height of the rectangle: "))
    area = width * height
    answer = area
    return answer

def calc_perimeter(answer):
    width = float(input("\nEnter the width of the rectangle: "))
    height = float(input("\nEnter the height of the rectangle: "))
    perimeter = 2 * (width + height)
    answer = perimeter
    return answer