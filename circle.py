
def calc_area(answer):
    radius = float(input("\nEnter the radius of the circle: "))
    area = 3.14159 * (radius ** 2)
    answer = area
    return answer

def calc_circumference(answer):
    radius = float(input("\nEnter the radius of the circle: "))
    circumference = 2 * 3.14159 * radius
    answer = circumference
    return answer
    
